errs = []
for i,(q,opts,ans) in enumerate(DATA):
    if len(opts)!=4: errs.append(f"Q{i+1} opts!=4")
    if len(set(opts))!=4: errs.append(f"Q{i+1} duplicated opts: {opts}")
    if ans not in opts: errs.append(f"Q{i+1} ans not in opts: {ans}")
    if len(q)>30: errs.append(f"Q{i+1} too long ({len(q)}): {q}")
if errs:
    print("ERRORS:"); [print(" ",e) for e in errs]; sys.exit(1)

def js(v):
    if isinstance(v,str): return json.dumps(v,ensure_ascii=False)
    return str(v)

lines = ["const SNORLAX_QUESTIONS=["]
for q,opts,ans in DATA:
    a = opts.index(ans)
    lines.append(f"  {{q:{js(q)},opts:[{','.join(js(o) for o in opts)}],a:{a}}},")
lines.append("];")
snor = "\n".join(lines)

# --- 讀 gym.html, 轉換 BOSS_QUESTIONS a:值→a:索引, 插入 SNORLAX_QUESTIONS ---
path = "/home/ubuntu/ptcg-opener/gym.html"
html = open(path, encoding="utf-8").read()

m = re.search(r"const BOSS_QUESTIONS=\[[\s\S]*?\n\];", html)
if not m: print("ERROR: BOSS_QUESTIONS block not found"); sys.exit(1)
block = m.group(0)
def conv(am):
    q = re.search(r"q:'([^']*)'", am).group(1)
    opts = [int(x) for x in re.findall(r"opts:\[([^\]]*)\]", am)[0].split(",")]
    a = int(re.search(r",a:(\d+)\}", am).group(1))
    if a not in opts: raise SystemExit(f"mecha ans {a} not in opts {opts} for {q[:20]}")
    return f"  {{q:'{q}',opts:[{','.join(map(str,opts))}],a:{opts.index(a)}}},"
qs = re.findall(r"\{q:'[^']*',opts:\[[^\]]*\],a:\d+\}", block)
new_block = "const BOSS_QUESTIONS=[\n" + "\n".join(conv(x) for x in qs) + "\n];"
print(f"mecha questions converted: {len(qs)}")
html = html.replace(block, new_block)

# 插入 SNORLAX_QUESTIONS 喺 BOSS_QUESTIONS 之後
html = html.replace(new_block, new_block + "\n\n// 武裝卡比獸題庫: 小四至小六奧數 120 題 (跨場旋轉池 ptcg_snorlaxPool)\n" + snor)

open(path, "w", encoding="utf-8").write(html)
